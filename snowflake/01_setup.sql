-- Step 3a: compute with a hard ceiling. Run once in Snowsight as ACCOUNTADMIN.
USE ROLE ACCOUNTADMIN;

-- XS warehouse that stops billing 60 s after the last query
CREATE WAREHOUSE IF NOT EXISTS CLICKSTREAM_WH
WAREHOUSE_SIZE = 'XSMALL'
AUTO_SUSPEND = 60
AUTO_RESUME = TRUE
INITIALLY_SUSPENDED = TRUE;

-- Suspends the warehouse at 40 credits (covers warehouse compute only, not Snowpipe)
CREATE RESOURCE MONITOR IF NOT EXISTS CLICKSTREAM_RM
WITH CREDIT_QUOTA = 40
FREQUENCY = MONTHLY
START_TIMESTAMP = IMMEDIATELY
TRIGGERS ON 80 PERCENT DO NOTIFY
ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE CLICKSTREAM_WH SET RESOURCE_MONITOR = CLICKSTREAM_RM;

CREATE DATABASE IF NOT EXISTS CLICKSTREAM;
CREATE SCHEMA IF NOT EXISTS CLICKSTREAM.RAW;
